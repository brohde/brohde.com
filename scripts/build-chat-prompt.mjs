// Codegen: bundle the chat system prompt + facts pack into the Pages Function.
//
// WHY a codegen step (not an esbuild text import): Cloudflare Pages Functions are
// bundled by esbuild with no reliable way to configure a text/markdown loader for the
// `functions/` build (no per-project rules like a standalone Worker's wrangler `rules`).
// So instead of duplicating the prompt/facts by hand (banned) or fighting the loader,
// we read the CANONICAL, FROZEN files in poc/chat/ (behavior signed off 38/38, #61) and
// emit a tiny generated TS module the Function imports. Single source of truth preserved:
// poc/chat/system-prompt.md + poc/chat/facts.md stay the only place this text is edited.
//
// Wired into `npm run build` (see package.json `build`), so it runs both locally and on
// the Cloudflare Pages build before Functions are compiled. Output is gitignored.
//
// The concatenation mirrors poc/chat/server.mjs exactly:
//   SYSTEM = <system-prompt.md> + "\n\n# FACTS PACK\n\n" + <facts.md>

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const pocDir = path.join(repoRoot, "poc", "chat");
const outDir = path.join(repoRoot, "functions", "api");
const outFile = path.join(outDir, "_chat-prompt.generated.ts");

const systemPrompt = readFileSync(
  path.join(pocDir, "system-prompt.md"),
  "utf8"
);
const facts = readFileSync(path.join(pocDir, "facts.md"), "utf8");
const SYSTEM = systemPrompt + "\n\n# FACTS PACK\n\n" + facts;

const banner =
  "// AUTO-GENERATED by scripts/build-chat-prompt.mjs — DO NOT EDIT.\n" +
  "// Source of truth: poc/chat/system-prompt.md + poc/chat/facts.md (behavior frozen, #61).\n" +
  "// Regenerated on every `npm run build`. Gitignored; never hand-maintained.\n";

mkdirSync(outDir, { recursive: true });
writeFileSync(
  outFile,
  banner + "export const SYSTEM = " + JSON.stringify(SYSTEM) + ";\n",
  "utf8"
);

console.log(
  `build-chat-prompt: wrote ${path.relative(repoRoot, outFile)} (${SYSTEM.length} chars)`
);
